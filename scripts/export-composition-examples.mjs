// Dedicated Chromium CDP session required on port 9224. No npm dependencies.
import fs from 'node:fs/promises';
import path from 'node:path';
import {spawn} from 'node:child_process';
const base=process.env.GALLERY_URL||'https://www.kagan.in/iwrzwr/visual-archive/';
const examples=path.resolve('examples');
await fs.mkdir(examples,{recursive:true});
const tab=await fetch('http://127.0.0.1:9224/json/new?about:blank',{method:'PUT'}).then(r=>r.json());
const socket=new WebSocket(tab.webSocketDebuggerUrl),pending=new Map();let next=0;
socket.addEventListener('message',event=>{const data=JSON.parse(event.data);if(data.id){const p=pending.get(data.id);pending.delete(data.id);data.error?p.reject(Error(JSON.stringify(data.error))):p.resolve(data.result);}});
await new Promise(resolve=>socket.addEventListener('open',resolve,{once:true}));
const call=(method,params={})=>new Promise((resolve,reject)=>{const id=++next;pending.set(id,{resolve,reject});socket.send(JSON.stringify({id,method,params}));});
async function evaluate(expression){const r=await call('Runtime.evaluate',{expression,returnByValue:true,awaitPromise:true});if(r.exceptionDetails)throw Error(r.exceptionDetails.exception?.description||r.exceptionDetails.text);return r.result.value;}
const wait=ms=>new Promise(resolve=>setTimeout(resolve,ms));
await call('Page.enable');await call('Runtime.enable');
await call('Emulation.setDeviceMetricsOverride',{width:1080,height:1080,deviceScaleFactor:1,mobile:false});
try{
 for(const id of ['signal-assembly','phase-mechanics','orbital-memory']){
  const output=path.join(examples,`${id}.mp4`);
  try{await fs.access(output);throw Error(`Output exists: ${output}`);}catch(error){if(error.code!=='ENOENT')throw error;}
  await call('Page.navigate',{url:new URL(`studies/${id}.html`,base).href});
  let ready=false;for(let i=0;i<100;i++){ready=await evaluate(`!!document.getElementById('${id}')?.compositionPreview`);if(ready)break;await wait(100);}if(!ready)throw Error(`Composition missing: ${id}`);
  const frames=await fs.mkdtemp('/tmp/iwrzwr-example-');
  for(let frame=0;frame<600;frame++){
   const png=await evaluate(`(()=>{const root=document.getElementById('${id}');root.compositionPreview.renderAt(${frame}/30);return root.querySelector('canvas').toDataURL('image/png');})()`);
   await fs.writeFile(path.join(frames,`frame-${String(frame).padStart(4,'0')}.png`),Buffer.from(png.split(',')[1],'base64'));
  }
  await new Promise((resolve,reject)=>{const encoder=spawn('swift',['encode-thermal-core.swift',frames,output],{stdio:'inherit',env:{...process.env,EXPORT_FRAME_COUNT:'600'}});encoder.on('error',reject);encoder.on('exit',code=>code===0?resolve():reject(Error(`Encoder exited ${code}; frames preserved in ${frames}`)));});
  // Only remove the 600 files generated by this successful export, never other work.
  for(let frame=0;frame<600;frame++)await fs.unlink(path.join(frames,`frame-${String(frame).padStart(4,'0')}.png`));
  await fs.rmdir(frames);
  console.log(JSON.stringify({id,output,frames:600,fps:30,seconds:20,bytes:(await fs.stat(output)).size}));
 }
}finally{socket.close();await fetch(`http://127.0.0.1:9224/json/close/${tab.id}`);}
